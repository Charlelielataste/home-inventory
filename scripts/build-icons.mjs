const out = {};
const missing = [];
for (const [key, src] of Object.entries(ICONS)) {
  const [set, name] = src.split(':');
  const data = sets[set];
  const icon = data.icons[name] ?? data.icons[data.aliases?.[name]?.parent];
  if (!icon) {
    missing.push(src);
    continue;
  }
  const w = icon.width ?? data.width ?? 16;
  const h = icon.height ?? data.height ?? 16;
  // Phosphor duotone: the light layer is drawn at 20% opacity → placeholder recolored at runtime.
  const body = icon.body.replaceAll('opacity=".2"', 'fill="__DUO__"');
  out[key] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${body}</svg>`;
}
if (missing.length) {
  console.error('Missing icons:', missing.join(', '));
  process.exit(1);
}

const header = `// GENERATED by scripts/build-icons.mjs — do not edit by hand.
// Fluent Emoji (c) Microsoft, MIT · Phosphor Icons, MIT.
`;
const file = new URL('../src/ui/icons-data.ts', import.meta.url);
writeFileSync(
  file,
  `${header}\nexport const ICON_SVGS = ${JSON.stringify(out, null, 1)} as const;\n\nexport type IconName = keyof typeof ICON_SVGS;\n`,
);
const size = readFileSync(file).length;
