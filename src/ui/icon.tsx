import { SvgXml } from 'react-native-svg';

import { ICON_SVGS, type IconName } from './icons-data';
import { colors } from './theme';

export type { IconName };

/** Icon name stored in the database (custom icon): may come from a newer build or a backup. */
export function isIconName(name: string | null | undefined): name is IconName {
  return !!name && Object.prototype.hasOwnProperty.call(ICON_SVGS, name);
}

type Props = {
  name: IconName;
  size?: number;
  /** Glyph color of Phosphor icons (Fluent illustrations keep their own colors). */
  color?: string;
  /** Light layer of Phosphor duotone icons. */
  duo?: string;
  /** Dims colored illustrations (e.g. inactive tab). */
  opacity?: number;
};

/**
 * Single icon component of the app.
 * Icons come from `icons-data.ts`, generated by `scripts/build-icons.mjs`
 * (Fluent Emoji illustrations + Phosphor UI glyphs). Add a key there and rerun the script.
 */
export function Icon({ name, size = 24, color = colors.text, duo = colors.duo, opacity }: Props) {
  const xml = ICON_SVGS[name].replaceAll('__DUO__', duo);
  return <SvgXml xml={xml} width={size} height={size} color={color} opacity={opacity} />;
}
